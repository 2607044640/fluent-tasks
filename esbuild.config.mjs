import esbuild from "esbuild";
import process from "process";
import module from "module";
import esbuildSvelte from "esbuild-svelte";
import sveltePreprocess from "svelte-preprocess";

const builtins = module.builtinModules;

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

import fs from "fs";

const copyCssPlugin = {
	name: 'copy-css',
	setup(build) {
		build.onEnd(() => {
			try {
				if (fs.existsSync("src/styles.css")) {
					fs.copyFileSync("src/styles.css", "styles.css");
					fs.copyFileSync("src/styles.css", "main.css");
					console.log("Copied src/styles.css to styles.css and main.css successfully.");
				} else if (fs.existsSync("main.css")) {
					fs.copyFileSync("main.css", "styles.css");
					console.log("Copied main.css to styles.css successfully.");
				}
			} catch (e) {
				console.error("Failed to copy CSS:", e);
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	plugins: [
		esbuildSvelte({
			compilerOptions: { css: "injected" },
			preprocess: sveltePreprocess(),
		}),
		copyCssPlugin,
	],
});

if (prod) {
	// Pre-build verification: enforce zero ESLint errors (including obsidianmd/no-static-styles-assignment)
	const { ESLint } = await import("eslint");
	const eslint = new ESLint();
	const results = await eslint.lintFiles(["src/**/*.{ts,js}"]);
	const errorCount = results.reduce((sum, r) => sum + r.errorCount, 0);
	if (errorCount > 0) {
		const formatter = await eslint.loadFormatter("stylish");
		const resultText = formatter.format(results.filter(r => r.errorCount > 0));
		console.error("❌ Build failed: ESLint detected blocking errors:\n", resultText);
		process.exit(1);
	}

	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
